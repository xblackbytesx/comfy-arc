#!/usr/bin/env bash
# Regenerate requirements.lock: every Python package in the image, with hashes.
#
#   scripts/lock.sh           resolve and rewrite requirements.lock (needs uv)
#   scripts/lock.sh --check   offline: does the lock match the Dockerfile pins
#                             and nodes.list? (CI runs this)
#
# Inputs are the PyTorch ARGs and COMFYUI_VERSION in the Dockerfile, ComfyUI's
# requirements.txt at that tag, and each node's requirements.txt at its commit.
# Run it after changing any of them. Wheels only, for the Python the Fedora
# base ships, so the build never compiles a dependency from source.
set -euo pipefail

cd "$(dirname "$0")/.."

PYTHON_VERSION=3.14
PLATFORM=x86_64-manylinux_2_28
PYPI_INDEX_URL=https://pypi.org/simple
LOCK=requirements.lock

arg() {
  local value
  value=$(sed -nE "s/^ARG $1=(.+)$/\1/p" Dockerfile)
  [[ -n $value ]] || { echo "lock: ARG $1 not found in Dockerfile" >&2; exit 1; }
  printf '%s' "$value"
}

COMFYUI_VERSION=$(arg COMFYUI_VERSION)
TORCH_VERSION=$(arg TORCH_VERSION)
TORCHVISION_VERSION=$(arg TORCHVISION_VERSION)
TORCHAUDIO_VERSION=$(arg TORCHAUDIO_VERSION)
TORCH_INDEX_URL=$(arg TORCH_INDEX_URL)

node_lines() { { grep -vE '^\s*(#|$)' nodes.list || true; }; }

# What the lock was generated from. Anything that changes the resolution
# changes this line, so a stale lock is caught without touching the network.
stamp() {
  {
    echo "python=$PYTHON_VERSION platform=$PLATFORM"
    echo "comfyui=$COMFYUI_VERSION torch=$TORCH_VERSION torchvision=$TORCHVISION_VERSION torchaudio=$TORCHAUDIO_VERSION"
    node_lines
  } | sha256sum | cut -c1-16
}

if [[ ${1:-} == --check ]]; then
  want="# inputs: $(stamp)"
  have=$(grep -m1 '^# inputs: ' "$LOCK" || true)
  if [[ $have != "$want" ]]; then
    echo "::error::$LOCK does not match the Dockerfile pins and nodes.list; run scripts/lock.sh"
    echo "lock has: ${have:-nothing}, pins give: $want"
    exit 1
  fi
  echo "$LOCK matches the pins ($want)"
  exit 0
fi

command -v uv >/dev/null || { echo "lock: needs uv (https://docs.astral.sh/uv/)" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

{
  echo "torch==${TORCH_VERSION}+xpu"
  echo "torchvision==${TORCHVISION_VERSION}+xpu"
  echo "torchaudio==${TORCHAUDIO_VERSION}+xpu"
  # Build tooling the Dockerfile used to upgrade unpinned.
  printf '%s\n' pip setuptools wheel packaging
} > "$work/requirements.in"

echo "== ComfyUI $COMFYUI_VERSION"
curl -fsSL "https://raw.githubusercontent.com/Comfy-Org/ComfyUI/${COMFYUI_VERSION}/requirements.txt" \
  > "$work/comfyui.txt"
echo "-r comfyui.txt" >> "$work/requirements.in"

while IFS=' ' read -r name url sha; do
  echo "== $name @ $sha"
  git clone --quiet "$url" "$work/$name"
  git -C "$work/$name" checkout --quiet --detach "$sha"
  if [[ -f $work/$name/requirements.txt ]]; then
    cp "$work/$name/requirements.txt" "$work/node-$name.txt"
    echo "-r node-$name.txt" >> "$work/requirements.in"
  fi
done < <(node_lines)

# unsafe-best-match lets one resolution see both indexes: the +xpu builds and
# the Intel runtime wheels come from the PyTorch index, everything else from
# PyPI. The hashes are what make that safe at install time.
(cd "$work" && uv pip compile requirements.in \
  --python-version "$PYTHON_VERSION" --python-platform "$PLATFORM" \
  --only-binary :all: --generate-hashes --no-header --no-annotate \
  --index-url "$PYPI_INDEX_URL" --extra-index-url "$TORCH_INDEX_URL" \
  --index-strategy unsafe-best-match --quiet \
  -o resolved.txt)

{
  echo "# Generated by scripts/lock.sh; do not edit. Every package in the image."
  echo "# inputs: $(stamp)"
  cat "$work/resolved.txt"
} > "$LOCK"

echo "wrote $LOCK: $(grep -cE '^[A-Za-z0-9]' "$LOCK") packages"
